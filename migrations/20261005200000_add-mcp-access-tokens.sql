-- Personal access tokens for the platform's MCP endpoint (/api/mcp).
--
-- An MCP client (Claude Code, Claude Desktop, Cursor, …) cannot carry the
-- browser's session cookies, so a member issues a token to it instead. The
-- token is only ever a bearer for *that member*: the Next.js route resolves it
-- here, then signs a short-lived JWT for the same user, and every read and
-- write runs under that member's own RLS exactly as it does in the browser.
-- A token therefore never grants more than its owner already has, and
-- deactivating a member cuts their tokens off on the next request.
--
-- Only a SHA-256 hash is stored. The plaintext is shown once at creation and
-- cannot be recovered; a lost token is revoked and replaced.

CREATE TABLE public.mcp_access_tokens (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 80),
  token_hash TEXT NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  token_prefix TEXT NOT NULL CHECK (token_prefix ~ '^c92_[A-Za-z0-9_-]{4,16}$'),
  -- 'read' tokens see only the read tools; 'write' tokens may also create and
  -- update tasks, post status updates and draft knowledge notes.
  scope TEXT NOT NULL CHECK (scope IN ('read', 'write')),
  expires_at TIMESTAMPTZ NOT NULL,
  last_used_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX mcp_access_tokens_user_idx ON public.mcp_access_tokens (user_id, created_at DESC);

ALTER TABLE public.mcp_access_tokens ENABLE ROW LEVEL SECURITY;

CREATE POLICY "members read their own MCP tokens"
ON public.mcp_access_tokens FOR SELECT TO authenticated
USING (user_id = (SELECT auth.uid()));

-- The hash is never readable by a client role, not even its owner's: it is
-- the only thing standing between a leaked row and a working credential.
-- Writes go through the functions below.
REVOKE ALL ON public.mcp_access_tokens FROM PUBLIC, anon, authenticated;
GRANT SELECT (id, user_id, name, token_prefix, scope, expires_at, last_used_at, revoked_at, created_at)
ON public.mcp_access_tokens TO authenticated;

-- ============================================================
-- create_mcp_access_token — the caller issues a token to themselves
-- ============================================================
-- The plaintext is generated by the server action and never reaches the
-- database; only its hash and a display prefix arrive here. user_id comes from
-- auth.uid(), so a token cannot be issued on someone else's behalf.
CREATE OR REPLACE FUNCTION public.create_mcp_access_token(
  p_name TEXT,
  p_token_hash TEXT,
  p_token_prefix TEXT,
  p_scope TEXT,
  p_expires_at TIMESTAMPTZ
)
RETURNS UUID
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_id UUID;
BEGIN
  IF NOT public.is_active_member() THEN
    RAISE EXCEPTION 'not an active member' USING ERRCODE = '42501';
  END IF;
  IF p_expires_at <= now() OR p_expires_at > now() + INTERVAL '366 days' THEN
    RAISE EXCEPTION 'invalid expiry' USING ERRCODE = '22023';
  END IF;
  -- Serialise issuance per user so two concurrent requests cannot both pass
  -- the cap below.
  PERFORM pg_advisory_xact_lock(hashtextextended('mcp_access_tokens:' || (SELECT auth.uid())::text, 0));
  IF (
    SELECT count(*) FROM public.mcp_access_tokens
    WHERE user_id = (SELECT auth.uid()) AND revoked_at IS NULL AND expires_at > now()
  ) >= 10 THEN
    RAISE EXCEPTION 'token limit reached' USING ERRCODE = '54000';
  END IF;

  INSERT INTO public.mcp_access_tokens (user_id, name, token_hash, token_prefix, scope, expires_at)
  VALUES ((SELECT auth.uid()), btrim(p_name), p_token_hash, p_token_prefix, p_scope, p_expires_at)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.create_mcp_access_token(TEXT, TEXT, TEXT, TEXT, TIMESTAMPTZ) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_mcp_access_token(TEXT, TEXT, TEXT, TEXT, TIMESTAMPTZ) TO authenticated;

-- ============================================================
-- revoke_mcp_access_token — owners only, idempotent
-- ============================================================
CREATE OR REPLACE FUNCTION public.revoke_mcp_access_token(p_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
  WITH revoked AS (
    UPDATE public.mcp_access_tokens
    SET revoked_at = now()
    WHERE id = p_id AND user_id = (SELECT auth.uid()) AND revoked_at IS NULL
    RETURNING 1
  )
  SELECT EXISTS (SELECT 1 FROM revoked);
$$;

REVOKE ALL ON FUNCTION public.revoke_mcp_access_token(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.revoke_mcp_access_token(UUID) TO authenticated;

-- ============================================================
-- resolve_mcp_access_token — the MCP route's only privileged call
-- ============================================================
-- Restricted to project_admin (the route's admin client). Given a hash it
-- answers with an owner only while the token is unrevoked, unexpired and the
-- owner is still an active member — so deactivation is immediate. Usage is
-- stamped at most once a minute to keep a chatty client from turning every
-- tool call into a write.
CREATE OR REPLACE FUNCTION public.resolve_mcp_access_token(p_token_hash TEXT)
RETURNS TABLE (token_id UUID, user_id UUID, scope TEXT, display_name TEXT)
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
#variable_conflict use_column
BEGIN
  RETURN QUERY
  WITH found AS (
    SELECT t.id, t.user_id, t.scope, m.display_name
    FROM public.mcp_access_tokens t
    JOIN public.team_members m ON m.user_id = t.user_id AND m.is_active
    WHERE t.token_hash = p_token_hash
      AND t.revoked_at IS NULL
      AND t.expires_at > now()
  ), touched AS (
    UPDATE public.mcp_access_tokens t
    SET last_used_at = now()
    FROM found
    WHERE t.id = found.id
      AND (t.last_used_at IS NULL OR t.last_used_at < now() - INTERVAL '1 minute')
    RETURNING t.id
  )
  SELECT found.id, found.user_id, found.scope, found.display_name FROM found;
END;
$$;

REVOKE ALL ON FUNCTION public.resolve_mcp_access_token(TEXT) FROM PUBLIC, anon, authenticated;
